import assert from 'node:assert/strict';
export async function checkPaneActivityBar({evaluate,waitFor,cdp,viewport,screenshot,configure}) {
  await cdp('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'no-preference'}]});
  configure('working','#39b5a4');
  await viewport(1280,900);await cdp('Page.reload');
  const bar='.pane-card[data-run-id="fixture-0"] .pane-group-activity';
  const style=property=>evaluate(`getComputedStyle(document.querySelector('${bar}'),'::after').${property}`);
  await waitFor(`!!document.querySelector('${bar}')`);
  await waitFor(`!!document.querySelector('[data-run-id="fixture-0"] iframe')?.contentDocument?.querySelector('textarea')`);
  await evaluate(`window.barFrame=document.querySelector('[data-run-id="fixture-0"] iframe');document.querySelector('[data-run-id="fixture-0"] .pane-input textarea').value='activity draft'`);
  await evaluate(`document.querySelector('#btn-refresh').click()`);
  await waitFor(`document.querySelector('[data-run-id="fixture-0"]').classList.contains('busy')`);
  assert.equal(await style('animationName'),'pane-group-running');
  assert.match(await evaluate(`getComputedStyle(document.querySelector('${bar}')).backgroundImage`),/50%/,'Diagonal split colors retained');
  assert.equal(await evaluate(`document.querySelector('${bar}').getBoundingClientRect().height`),3);
  const size=await evaluate(`({w:barFrame.clientWidth,h:barFrame.clientHeight})`);
  await evaluate(`window.barAnimation=document.getAnimations().find(a=>a.effect?.target===document.querySelector('${bar}'));barAnimation.pause();barAnimation.currentTime=300`);
  const left=await style('transform');
  await evaluate('barAnimation.currentTime=1200');
  const right=await style('transform');
  const tx=s=>Number(s.split(',')[4]);assert.ok(tx(right)>tx(left),'Highlight moves left to right');
  await evaluate('barAnimation.play()');
  await screenshot('pane-group-running');
  configure('waiting_user','#ff8800');await evaluate(`document.querySelector('#btn-refresh').click()`);
  await waitFor(`!document.querySelector('[data-run-id="fixture-0"]').classList.contains('busy')`);
  assert.equal(await style('animationName'),'none');
  assert.match(await evaluate(`getComputedStyle(document.querySelector('${bar}')).backgroundImage`),/255, 136, 0/);
  assert.equal(await evaluate(`document.querySelector('[data-run-id="fixture-0"] iframe')===barFrame`),true);
  assert.deepEqual(await evaluate(`({w:barFrame.clientWidth,h:barFrame.clientHeight})`),size,'Activity and color changes preserve terminal geometry');
  assert.equal(await evaluate(`document.querySelector('[data-run-id="fixture-0"] .pane-input textarea').value`),'activity draft');
  configure('background_working','#ff8800');await evaluate(`document.querySelector('#btn-refresh').click()`);
  await waitFor(`document.querySelector('[data-run-id="fixture-0"]').classList.contains('background-working')`);
  assert.equal(await style('animationName'),'pane-group-running');
  await cdp('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]});
  assert.equal(await style('animationName'),'none');
  await cdp('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'no-preference'}]});
  await evaluate(`document.querySelector('[data-run-id="fixture-0"] .btn-zoom').click()`);
  await waitFor(`!!document.querySelector('.zoomed-pane .pane-group-activity')`);
  assert.equal(await style('animationName'),'pane-group-running');
  await screenshot('pane-group-running-zoom');
  console.log('PASS: group strip colors/split, running and background animation, left-to-right motion, waiting stop, reduced motion, zoom, stable frame/geometry/draft');
}
