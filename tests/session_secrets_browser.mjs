import assert from 'node:assert/strict';
export async function checkSessionSecrets({evaluate,waitFor,viewport,cdp,screenshot,configure,submissions,sentPrompts,frameCount}) {
  await viewport(1280,900);
  configure([]);
  await evaluate(`localStorage.setItem('orch_layout','cols-2');localStorage.setItem('orch_slots',JSON.stringify(['fixture-0','fixture-1']))`);
  await cdp('Page.reload');
  const card='[data-run-id="fixture-0"]';
  await waitFor(`!!document.querySelector('${card} iframe')`);
  const frames=frameCount(), prompts=sentPrompts.length;
  const sample = id => ({id, run_id:'fixture-0',name:'API_TOKEN',cwd:'/fixture/project',argv:['/usr/bin/python3','check_api.py'],reason:'Check API access <literal>',timeout:60,state:'pending',exit_code:null,session_value_available:false,keychain_supported:true});
  await evaluate(`document.querySelector('[data-run-id="fixture-1"] .pane-input textarea').focus()`);
  configure([sample('a'.repeat(32))]);
  await waitFor(`!!document.querySelector('${card} .session-secrets-dialog[open]')`,10000);
  assert.equal(await evaluate(`document.activeElement.closest('.pane-card').dataset.runId`),'fixture-1','Automatic requests preserve typing focus');
  assert.equal(await evaluate(`document.querySelector('${card} .session-secrets-dialog').matches(':modal')`),false);
  assert.equal(await evaluate(`document.querySelector('${card} [data-value]').type`),'password');
  assert.equal(await evaluate(`document.querySelector('${card} [data-save]').checked`),false);
  assert.equal(await evaluate(`document.querySelector('${card} [data-reason]').textContent`),'Check API access <literal>');
  await evaluate(`document.querySelector('${card} .pane-input textarea').value='ordinary draft';document.querySelector('[data-run-id="fixture-1"] .pane-input textarea').focus()`);
  assert.equal(await evaluate(`document.activeElement.closest('.pane-card').dataset.runId`),'fixture-1');
  await evaluate(`document.querySelector('${card} [data-value]').value='fixture-only-private';document.querySelector('${card} [data-approve]').click();document.querySelector('${card} [data-approve]').click()`);
  await waitFor(`document.querySelector('${card} [data-status]').textContent.includes('running')`);
  assert.equal(submissions.length,1);
  assert.equal(submissions[0].body.value,'fixture-only-private');
  assert.equal(submissions[0].intent,'approve-secret');
  assert.equal(submissions[0].body.save,false);
  assert.equal(await evaluate(`document.querySelector('${card} [data-value]').value`),'');
  assert.equal(await evaluate(`JSON.stringify(localStorage).includes('fixture-only-private')`),false);
  assert.equal(sentPrompts.length,prompts);
  assert.equal(frameCount(),frames);
  assert.equal(await evaluate(`document.querySelector('${card} .pane-input textarea').value`),'ordinary draft');
  configure([{...sample('a'.repeat(32)),state:'completed',exit_code:0,session_value_available:true}]);
  await waitFor(`document.querySelector('${card} [data-status]').textContent.includes('exit 0')`,10000);
  await screenshot('session-secret-completed');
  await evaluate(`document.querySelector('${card} [data-close]').click()`);
  configure([sample('b'.repeat(32))]);
  await waitFor(`!!document.querySelector('${card} .session-secrets-dialog[open]')`,10000);
  await screenshot('session-secret-approval');
  await evaluate(`window.secretField=document.querySelector('${card} [data-value]');secretField.value='fixture-hidden';document.querySelector('${card}').style.display='none'`);
  await waitFor(`!document.querySelector('${card} .session-secrets-dialog')`);
  assert.equal(await evaluate('secretField.value'),'');
  await evaluate(`document.querySelector('${card}').style.display='';document.querySelector('${card} .btn-pane-more').click();document.querySelector('${card} .btn-session-secrets').click()`);
  await waitFor(`!!document.querySelector('${card} .session-secrets-dialog[open]')`);
  await evaluate(`document.querySelector('${card} [data-source]').value='keychain';document.querySelector('${card} [data-source]').dispatchEvent(new Event('change'))`);
  assert.equal(await evaluate(`document.querySelector('${card} [data-value]').disabled`),true);
  await evaluate(`document.querySelector('${card} [data-approve]').click()`);
  await waitFor(`document.querySelector('${card} [data-status]').textContent.includes('running')`);
  assert.equal(submissions.at(-1).body.source,'keychain');
  assert.equal(submissions.at(-1).body.value,'');
  await evaluate(`document.querySelector('${card} [data-cancel]').click()`);
  await waitFor(`document.querySelector('${card} [data-status]').textContent.includes('cancelled')`);
  await evaluate(`document.querySelector('${card} [data-close]').click()`);
  configure([sample('c'.repeat(32))]);
  await viewport(900,844);
  await waitFor(`!!document.querySelector('${card} .session-secrets-dialog[open]')`,10000);
  assert.ok(await evaluate(`(()=>{const c=document.querySelector('${card}').getBoundingClientRect(),d=document.querySelector('${card} .session-secrets-dialog').getBoundingClientRect();return d.left>=c.left&&d.right<=c.right&&d.top>=c.top&&d.bottom<=c.bottom;})()`));
  await screenshot('session-secret-narrow');
  await evaluate(`window.secretField=document.querySelector('${card} [data-value]');secretField.value='fixture-private-escape';secretField.focus()`);
  await cdp('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27});
  await waitFor(`!document.querySelector('${card} .session-secrets-dialog')`);
  assert.equal(await evaluate('secretField.value'),'');
  configure([]);
  console.log('PASS: automatic session approval card, exact command, masked input, default no persistence, single approval, safe reuse, cancellation, no chat/storage/iframe mutation and hidden-pane cleanup');
}
