import assert from 'node:assert/strict';
export async function checkWorkingDirectory({evaluate,waitFor,cdp,viewport,screenshot,submissions,requests,mode,configure}) {
  await waitFor(`!!document.querySelector('#session-list .session-item')`);
  configure();
  await viewport(1280,900);
  await evaluate(`localStorage.clear();localStorage.setItem('orch_layout','cols-2');localStorage.setItem('orch_slots',JSON.stringify(['cwd-agent','cwd-terminal']));localStorage.setItem('siling_appearance_v1',JSON.stringify({language:'en'}))`);
  await cdp('Page.reload');
  await waitFor(`document.querySelectorAll('#grid .pane iframe').length===2`);
  await evaluate(`window.cwdFrame=document.querySelector('[data-run-id="cwd-agent"] iframe');document.querySelector('[data-run-id="cwd-agent"] .pane-input textarea').value='keep draft'`);
  const open=async(id='cwd-agent')=>{
    await evaluate(`document.querySelector('[data-run-id="${id}"] .btn-pane-more').click();document.querySelector('[data-run-id="${id}"] .btn-working-directory').click()`);
    await waitFor(`document.querySelector('#working-directory-dialog').open`);
    assert.equal(await evaluate(`!!document.querySelector('.pane-menu[open]')`),false);
  };
  await open();
  assert.equal(await evaluate(`document.querySelector('#working-directory-path').value`),'/original');
  await evaluate(`document.querySelector('#working-directory-dialog .cwd-cancel').click()`);
  assert.equal(submissions.length,0);
  await open();mode('error');
  await evaluate(`document.querySelector('#working-directory-path').value='/new project';document.querySelector('#working-directory-dialog form').requestSubmit()`);
  await waitFor(`!document.querySelector('#working-directory-dialog .cwd-error').hidden`);
  assert.equal(await evaluate(`document.querySelector('#working-directory-path').value`),'/new project');
  mode('ok');
  const restarts=requests.filter(r=>r.path.endsWith('/restart')).length;
  await evaluate(`document.querySelector('#working-directory-dialog form').requestSubmit();document.querySelector('#working-directory-dialog form').requestSubmit()`);
  await waitFor(`!document.querySelector('#working-directory-dialog').open`);
  assert.equal(submissions.length,2,'Pending submission is sent once');
  assert.equal(requests.filter(r=>r.path.endsWith('/restart')).length,restarts,'Save alone never restarts');
  assert.equal(await evaluate(`document.querySelector('[data-run-id="cwd-agent"] iframe')===cwdFrame`),true);
  assert.equal(await evaluate(`document.querySelector('[data-run-id="cwd-agent"] .pane-input textarea').value`),'keep draft');
  await open();
  assert.equal(await evaluate(`document.querySelector('#working-directory-path').value`),'/new project');
  await evaluate(`window.cwdOldConfirm=window.confirm;window.cwdConfirms=[];window.confirm=text=>{cwdConfirms.push(text);return false};document.querySelector('#working-directory-dialog input[type=checkbox]').checked=true;document.querySelector('#working-directory-dialog form').requestSubmit()`);
  await waitFor(`cwdConfirms.length===1`);
  assert.equal(requests.filter(r=>r.path.endsWith('/restart')).length,restarts,'Declining restart keeps process running');
  await evaluate(`window.confirm=cwdOldConfirm`);
  await open('cwd-terminal');
  assert.equal(await evaluate(`document.querySelector('#working-directory-dialog .cwd-restart').hidden`),true);
  assert.ok(await evaluate(`document.querySelector('#working-directory-help').textContent.includes('SSH')`));
  await viewport(390,844);await screenshot('working-directory-terminal');
  assert.ok(await evaluate(`document.querySelector('#working-directory-dialog').getBoundingClientRect().width<=innerWidth`));
  await evaluate(`document.querySelector('#working-directory-dialog .cwd-cancel').click()`);
  await viewport(1280,900);
  await evaluate(`localStorage.setItem('siling_appearance_v1',JSON.stringify({language:'zh'}))`);
  await cdp('Page.reload');
  await waitFor(`document.querySelectorAll('#grid .pane iframe').length===2`);
  await open();
  assert.equal(await evaluate(`document.querySelector('#working-directory-heading').textContent`),'更改工作目录');
  await viewport(390,844);await screenshot('working-directory-chinese');
  await evaluate(`document.querySelector('#working-directory-dialog .cwd-cancel').click()`);
  console.log('PASS: working directory cancel, validation retry, duplicate guard, persistence, frame/draft retention, explicit restart confirmation and Terminal guidance');
}
