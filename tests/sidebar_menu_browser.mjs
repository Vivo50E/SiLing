import assert from 'node:assert/strict';
export async function checkSidebarMenu({evaluate,waitFor,cdp,viewport,screenshot,configure}) {
  await waitFor(`!!document.querySelector('#session-list .session-item')`);
  configure();await viewport(1280,900);
  await evaluate(`localStorage.clear();localStorage.setItem('orch_layout','cols-2');localStorage.setItem('orch_slots',JSON.stringify(['side-0','side-1']));localStorage.setItem('siling_appearance_v1',JSON.stringify({language:'en'}))`);
  await cdp('Page.reload');await waitFor(`document.querySelectorAll('#grid .pane iframe').length===2`);
  await evaluate(`window.sideFrames=[...document.querySelectorAll('#grid .pane iframe')];window.sideSlots=localStorage.orch_slots;document.querySelector('[data-run-id="side-0"] .pane-input textarea').value='sidebar draft'`);
  const more=async(id)=>evaluate(`document.querySelector('.session-item[data-id="${id}"] .btn-session-more').click()`);
  await more('side-0');
  await waitFor(`!!document.querySelector('[data-run-id="side-0"] .pane-menu[open]')`);
  assert.equal(await evaluate(`localStorage.orch_slots===sideSlots`),true);
  await screenshot('sidebar-pane-more');
  await evaluate(`document.querySelector('.pane-menu[open] .btn-rename-session').click()`);
  await waitFor(`document.querySelector('#rename-session-dialog').open`);
  assert.equal(await evaluate(`document.querySelector('#rename-session-context').textContent`),'Sidebar 0');
  await evaluate(`document.querySelector('#rename-session-dialog [data-rename-cancel]').click()`);
  await more('side-0');
  await cdp('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27});
  await cdp('Input.dispatchKeyEvent',{type:'keyUp',key:'Escape',code:'Escape',windowsVirtualKeyCode:27});
  await waitFor(`document.activeElement===document.querySelector('.session-item[data-id="side-0"] .btn-session-more')`);
  assert.equal(await evaluate(`[...document.querySelectorAll('#grid .pane iframe')].every((f,i)=>f===sideFrames[i])`),true);
  assert.equal(await evaluate(`document.querySelector('[data-run-id="side-0"] .pane-input textarea').value`),'sidebar draft');
  await more('side-2');await waitFor(`document.querySelector('#sidebar-pane-menu').open`);
  assert.ok(await evaluate(`document.querySelector('#sidebar-pane-menu .pane-group-select').checkVisibility()`),'Unplaced sessions show Project group');
  assert.equal(await evaluate(`localStorage.orch_slots===sideSlots`),true,'Unplaced menu never pins or evicts a session');
  await evaluate(`document.querySelector('#sidebar-pane-menu [data-action="Change working directory"]').click()`);
  await waitFor(`document.querySelector('#working-directory-dialog').open`);
  assert.equal(await evaluate(`document.querySelector('#working-directory-dialog .cwd-context').textContent`),'Sidebar 2');
  assert.equal(await evaluate(`document.querySelector('#working-directory-dialog .cwd-restart').hidden`),true,'Unplaced sessions do not offer a restart requiring a pane');
  await evaluate(`document.querySelector('#working-directory-dialog .cwd-cancel').click()`);
  await more('side-2');
  await evaluate(`document.querySelector('#sidebar-pane-menu [data-action="Open pane"]').click()`);
  await waitFor(`!!document.querySelector('[data-run-id="side-2"] .pane-menu[open]')`);
  assert.deepEqual(await evaluate(`JSON.parse(localStorage.orch_slots)`),['side-0','side-1','side-2']);
  assert.equal(await evaluate(`document.querySelector('[data-run-id="side-0"] iframe')===sideFrames[0]`),true);
  await evaluate(`document.querySelector('.pane-menu[open]').close()`);
  await viewport(390,844);
  await more('side-0');await waitFor(`document.querySelector('#sidebar-pane-menu').open`);
  assert.ok(await evaluate(`document.querySelector('#sidebar-pane-menu .pane-group-select').checkVisibility()`),'Mobile sessions show Project group');
  await screenshot('sidebar-more-mobile');
  assert.ok(await evaluate(`(()=>{const r=document.querySelector('#sidebar-pane-menu').getBoundingClientRect();return r.width>0&&r.left>=0&&r.right<=innerWidth})()`));
  await evaluate(`document.querySelector('#sidebar-pane-menu').close()`);
  console.log('PASS: sidebar reuses pane menu, targets rename/directory correctly, restores focus, preserves frames/drafts, and never pins until Open pane');
}
